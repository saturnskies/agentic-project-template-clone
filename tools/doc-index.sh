#!/bin/sh
# Build docs/INDEX.md from the front matter of every doc under docs/ and tutorial/,
# so agents read one map instead of opening files to learn what they hold.
# Usage: tools/doc-index.sh           (rewrite docs/INDEX.md)
#        tools/doc-index.sh --check   (fail on a missing or bad header, or a stale index)
# Header fields: description (one line), status (current|draft|done|superseded),
# updated (YYYY-MM-DD), superseded_by (required when status is superseded).
set -u
export LC_ALL=C   # same sort order in Git Bash, Linux and CI, or --check reports a false "stale"
cd "$(dirname "$0")/.." || exit 2
index=docs/INDEX.md
sep="$(printf '\037')"   # field separator; unlike a tab, read keeps empty fields
nl='
'

# Sort by folder, then file, so each folder's docs stay under one heading.
docs() {
  find docs tutorial -name '*.md' ! -path "$index" ! -path 'tutorial/extras/*' |
    awk '{ d = $0; sub(/\/[^\/]*$/, "", d); print d "\t" $0 }' | sort | cut -f2
}

# Print the header fields joined by $sep, or nothing when the file has no closed front matter.
fields() {
  tr -d '\r' < "$1" | awk -v sep="$sep" '
    NR == 1 && $0 != "---" { exit }
    NR > 1 && $0 == "---" { done = 1; exit }
    NR > 1 { k = $0; sub(/:.*/, "", k); v = $0; sub(/^[^:]*:[ \t]*/, "", v); gsub(/^"|"$/, "", v); f[k] = v }
    END { if (done) print f["description"] sep f["status"] sep f["updated"] sep f["superseded_by"] }'
}

errors=0
bad() { echo "tools/doc-index.sh: $1: $2" >&2; errors=$((errors + 1)); }

render() {
  echo "# Docs Index"
  echo
  echo "Generated by \`tools/doc-index.sh\` from each doc's front matter; do not edit by hand."
  echo "Read this first, open only the docs a task needs, and never cite a superseded doc."
  echo "Status: **current** = in force or in progress; **draft** = proposed, not approved;"
  echo "**done** = finished plan or shipped slice spec, kept as history; **superseded** = replaced, follow the pointer."
  dir=""
  IFS="$nl"; set -f   # one path per line, even with spaces; no globbing
  for f in $(docs); do
    IFS="$sep" read -r desc st upd sup <<EOF
$(fields "$f")
EOF
    [ -n "$st$desc$upd" ] || { bad "$f" "no front matter; start the file with the header described in CLAUDE.md Conventions"; continue; }
    case "$desc" in ''|'>'|'|') bad "$f" "description must be one non-empty line" ;; esac
    case "$st" in current|draft|done) ;; superseded) [ -n "$sup" ] || bad "$f" "superseded without superseded_by" ;; *) bad "$f" "status '$st' is not current, draft, done or superseded" ;; esac
    echo "$upd" | grep -Eq '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' || bad "$f" "updated '$upd' is not YYYY-MM-DD"
    d="${f%/*}"
    [ "$d" = "$dir" ] || { dir="$d"; printf '\n## %s/\n\n' "$dir"; }
    note="$st"
    [ "$st" = superseded ] && note="superseded by $sup"
    rel="${f#docs/}"
    [ "$rel" = "$f" ] && rel="../$f"
    printf -- '- [%s](%s) — %s, %s — %s\n' "${f##*/}" "$rel" "$note" "$upd" "$desc"
  done
  unset IFS; set +f
  return $((errors > 0))
}

case "${1:-}" in
  --check)
    new="$(mktemp)"
    trap 'rm -f "$new"' EXIT
    render > "$new"
    if ! { tr -d '\r' < "$index"; } 2>/dev/null | cmp -s - "$new"; then
      echo "tools/doc-index.sh: $index is stale; run tools/doc-index.sh" >&2
      errors=$((errors + 1))
    fi
    [ $errors -eq 0 ] || exit 1
    echo "tools/doc-index.sh: all docs have headers and the index is current"
    ;;
  "")
    render > "$index"
    status=$?
    echo "tools/doc-index.sh: wrote $index"
    exit $status
    ;;
  *) echo "usage: tools/doc-index.sh [--check]" >&2; exit 2 ;;
esac
